// the band members: what he does + the style of his band
var (
	bandPart = map[string][2]string{
		"cantante": {"Voz", "Vocals"}, "guitarra": {"Guitarra", "Guitar"}, "bajo": {"Bajo", "Bass"}, "bateria": {"Batería", "Drums"},
	}
	bandStyle = map[string][2]string{
		"sp":  {"de punk-pop con flequillo", "of fringe punk-pop"},
		"off": {"de punk californiano", "of California punk"},
		"met": {"de metal de melena larga", "of long-haired metal"},
		"ps":  {"de punk marinero", "of sailor punk"},
		"bt":  {"de punk canadiense con rabia", "of angry Canadian punk"},
		"lp":  {"de rock galés melódico", "of melodic Welsh rock"},
		"des": {"de punk-rock de barrio", "of neighbourhood punk-rock"},
	}
)

func init() {
	for b, st := range bandStyle {
		for p, pt := range bandPart {
			if _, own := charDescs[b+"_"+p]; !own { // members with a line of their own keep it
				charDescs[b+"_"+p] = [2]string{pt[0] + " " + st[0], pt[1] + " " + st[1]}
			}
		}
	}
	for k, v := range map[string]string{
		"Aún no lo has visto":                 "Not seen yet",
		"Conseguido: elígelo en el vestuario": "Unlocked: pick him in the wardrobe",
		"Falta 1 muerte para conseguirlo":     "1 more kill to unlock him",
		"Faltan %d muertes para conseguirlo":  "%d more kills to unlock him",
		"ELIMINADO %d/%d":                     "ELIMINATED %d/%d",
	} {
		if _, ok := langDataEN[k]; !ok {
			langDataEN[k] = v
		}
	}
	for _, d := range charDescs {
		if _, ok := langDataEN[d[0]]; !ok {
			langDataEN[d[0]] = d[1]
		}
	}
}

// charDesc: the Spanish description of a character (tr() gives the English one); "" when he has none.
func charDesc(slug string) string {
	if d, ok := charDescs[slug]; ok {
		return d[0]
	}
	if i := strings.LastIndex(slug, "_"); i > 0 { // a band member of a band with no style line
		if p, ok := bandPart[slug[i+1:]]; ok {
			return p[0]
		}
	}
	return ""
}
